-- 0020_guest_access_fix4.sql — тот же класс проблемы, что 0017/0018/0019, найден финальным
-- ревью всей ветки guest-read-access: два места, где отзыв лишних прав по умолчанию пропустили.
--
-- app_settings (0016) — таблица кил-свитча, доступ задуман ТОЛЬКО через security definer
-- функции guest_access_enabled()/set_guest_access() ("без политик: доступ только через функции
-- ниже" — комментарий в 0016), но anon и authenticated по умолчанию получили полный табличный
-- SELECT/INSERT/UPDATE/DELETE/TRUNCATE/REFERENCES/TRIGGER напрямую. Сейчас неэксплуатируемо (RLS
-- включена, политик нет вообще ни для одной роли — запрещает всё), но если когда-нибудь на эту
-- таблицу добавят permissive-политику и забудут про эти фоновые права, кил-свитч можно будет
-- читать/писать в обход функций. Отзываем у обеих ролей на будущее.
revoke select, insert, update, delete, truncate, references, trigger
  on public.app_settings
  from anon, authenticated;

-- race_driver_pool — единственная таблица, которую 0016 сознательно НЕ открыл анониму (гостевые
-- страницы её не используют). anon-политики на неё нет и не было, но anon по умолчанию всё равно
-- получил табличный SELECT. Сейчас неэксплуатируемо (RLS блокирует за отсутствием anon-политики),
-- но это ровно та единственная таблица, где по плану должно быть закрыто наглухо — отзываем.
revoke select on public.race_driver_pool from anon;
